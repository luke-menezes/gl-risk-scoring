"""
Multi-seed benchmark, per voucher: the risk score against the baselines and the ablation variants.

    python scripts/run_benchmark.py            # about 5 to 30 minutes, depending on the machine; needs [ml]
    python scripts/run_benchmark.py --quick    # 3 seeds, small sweeps, for a smoke test

Writes docs/benchmark.csv (every run), docs/benchmark_results.md (the summary tables) and
docs/precision_at_k.png.
"""

from __future__ import annotations

import argparse
import platform
from importlib.metadata import version
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from glrisk import evaluate, plots, scoring, synthetic

DOCS = Path(__file__).resolve().parents[1] / "docs"
KS = list(range(10, 301, 10))
# About 1.2 anomalous vouchers per list place at every size, as in the default ledger (about 60 in
# about 7,550 vouchers, k = 50), so the sweeps test the ranking, not the ratio of anomalies to k
ANOMALIES_PER_PLACE = 1.2
RATE = 0.008     # the generator's default, per voucher


def size_sweep_rate(n_rows: int) -> float:
    """Anomaly rate (per voucher) giving ANOMALIES_PER_PLACE anomalous vouchers per place on the default list."""
    vouchers = n_rows / synthetic.MEAN_VOUCHER_LINES
    return round(ANOMALIES_PER_PLACE * scoring.priority_list_size(round(vouchers)) / vouchers, 6)


def table(summary: pd.DataFrame, rows: list[str]) -> str:
    """Markdown table: one row per ranking, mean ± SD at the default k."""
    lines = ["| Ranking | Precision@k | Recall@k |", "|---|---|---|"]
    by_name = summary.set_index("ranking")
    for name in rows:
        r = by_name.loc[name]
        lines.append(f"| {name} | {r['precision mean']:.3f} ± {r['precision std']:.3f} "
                     f"| {r['recall mean']:.3f} ± {r['recall std']:.3f} |")
    return "\n".join(lines)


def sweep_table(sweep: pd.DataFrame) -> str:
    """Markdown table of a sweep: ledger size and anomaly rate against precision, recall and share of ceiling."""
    lines = ["| Lines | Anomalous vouchers | Ranking | Precision@k | Recall@k | Share of ceiling | Seeds |",
             "|---|---|---|---|---|---|---|"]
    for _, r in sweep.iterrows():
        lines.append(f"| {r['n_rows']:,} | {r['anomaly_rate']:.2%} | {r['ranking']} "
                     f"| {r['precision mean']:.3f} ± {r['precision std']:.3f} "
                     f"| {r['recall mean']:.3f} ± {r['recall std']:.3f} "
                     f"| {r['share_of_ceiling mean']:.3f} ± {r['share_of_ceiling std']:.3f} | {r['seeds']} |")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--quick", action="store_true")
    args = parser.parse_args()
    seeds = range(3) if args.quick else range(30)
    big_seeds = range(2) if args.quick else range(10)    # 200k lines: about 30 s per seed
    big = 20_000 if args.quick else 200_000

    runs = [evaluate.run_once(20_000, RATE, s, ks=KS, ablation=True, ml=True) for s in seeds]
    base = pd.concat(runs, ignore_index=True)
    size_runs = [evaluate.run_once(n, size_sweep_rate(n), s) for n, ss in ((2_000, seeds), (big, big_seeds))
                 for s in ss]
    rate_runs = [evaluate.run_once(20_000, rate, s) for rate in (0.002, 0.004, 0.016) for s in seeds]
    results = pd.concat([base, *size_runs, *rate_runs], ignore_index=True)
    DOCS.mkdir(exist_ok=True)
    results.to_csv(DOCS / "benchmark.csv", index=False, float_format="%.4f")

    main_rows = ["Risk score", "Per-line score, listed by voucher", "Number of tests hit", "Isolation Forest",
                 "Amount only", "Random flagged vouchers", "Ceiling (flagged vouchers)"]
    ablation_rows = ["Risk score", *evaluate.VARIANTS]
    summary = evaluate.summarise(base)
    k = int(base["default_k"].iloc[0])
    sweep_rows = ["Risk score", "Number of tests hit", "Ceiling (flagged vouchers)"]

    def sweep_of(runs):
        table = evaluate.summarise(pd.concat(runs, ignore_index=True))
        return table[table["ranking"].isin(sweep_rows)]

    by_size = sweep_of([base, *size_runs]).sort_values("n_rows", kind="stable")
    by_rate = sweep_of([base, *rate_runs]).sort_values("anomaly_rate", kind="stable")

    # Robustness: generator settings drawn at random per seed, and priors perturbed at random
    stress = pd.concat([evaluate.run_once(20_000, seed=s, **evaluate.stress_settings(s)) for s in seeds])
    stress = stress[stress["k"] == stress["default_k"]].pivot(index="seed", columns="ranking", values="share_of_ceiling")
    lead = stress["Risk score"] - stress["Number of tests hit"]
    draws = 5 if args.quick else 20
    priors = pd.concat([evaluate.prior_sensitivity(20_000, s, draws) for s in seeds])
    # Voucher size: more lines, more chances to be flagged by chance
    bias = pd.concat([evaluate.size_bias(20_000, s) for s in seeds])
    vouchers = round(len(bias) / len(seeds))

    intro = (f"# Benchmark results\n\nGenerated by `scripts/run_benchmark.py`. Mean ± standard deviation "
             f"over {len(seeds)} seeds; ledgers of about 20,000 lines in about {vouchers:,} vouchers, 0.8% of "
             f"vouchers with injected anomalies, k = {k} vouchers (the default list size). Every figure is per "
             f"voucher.\n\nPython {platform.python_version()}; "
             + ", ".join(f"{p} {version(p)}" for p in ("numpy", "pandas", "holidays", "scikit-learn")) + ".\n")
    md = [intro,
          "## Rankings\n", table(summary, main_rows),
          "\n## Ablation (one design choice removed at a time)\n", table(summary, ablation_rows),
          "\n## Ledger size (about 1.2 anomalous vouchers per list place; k = the default list size)\n",
          sweep_table(by_size),
          f"\n## Anomaly rate (20,000 lines, k = {k})\n",
          sweep_table(by_rate)]

    def spread(x: pd.Series) -> str:
        return f"{x.mean():.3f} ± {x.std():.3f} (lowest {x.min():.3f})"

    md += ["\n## Robustness to the generator (settings drawn at random per seed)\n",
           "Anomalous vouchers 0.3-1.6%, silent share 5-25%, manual share 5-30%, background noise x0.5-2.",
           f"Ranges: practical judgement. Share of ceiling at k = {k}, because the anomaly rate varies.\n",
           "| Ranking | Share of ceiling |", "|---|---|",
           f"| Risk score | {spread(stress['Risk score'])} |",
           f"| Number of tests hit | {spread(stress['Number of tests hit'])} |",
           f"| Lead of the risk score | {spread(lead)}; ahead on {(lead > 0).sum()} of {len(lead)} ledgers |",
           f"\n## Prior sensitivity (every prior x a random factor in 0.5-1.5; {draws} draws per seed)\n",
           "| Measure | Value |", "|---|---|",
           f"| Precision@{k} | {spread(priors['precision'])} |",
           f"| Share of the default top {k} still listed | {spread(priors['overlap'])} |",
           "\n## Voucher size (more lines, more chances to be flagged by chance)\n",
           "| Lines per voucher | Share of vouchers | Share of the priority list | Normal vouchers flagged |",
           "|---|---|---|---|"]
    listed, normal = bias[bias["listed"]], bias[bias["normal"]]
    for size, group in bias.groupby("lines"):
        md.append(f"| {size} | {len(group) / len(bias):.1%} | {(listed['lines'] == size).mean():.1%} "
                  f"| {normal.loc[normal['lines'] == size, 'flagged'].mean():.1%} |")
    (DOCS / "benchmark_results.md").write_text("\n".join(md) + "\n", encoding="utf-8")

    curves = evaluate.summarise(base, default_k_only=False)
    curves = curves[curves["ranking"].isin(main_rows)]
    curves = curves.assign(order=curves["ranking"].map(main_rows.index)).sort_values(["order", "k"], kind="stable")
    plots.precision_at_k_curve(curves, k)
    plt.savefig(DOCS / "precision_at_k.png", dpi=110, bbox_inches="tight")
    print("\n".join(md))


if __name__ == "__main__":
    main()
